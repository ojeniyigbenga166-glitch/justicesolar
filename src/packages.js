import { trackPackageSelect } from './analytics.js';

export function initSolarPackages(openModalCallback) {
  // ─── Request a Quote Modal Bindings ─────────────────────────────────────────
  const quoteButtons = document.querySelectorAll('.package-card__btn');
  quoteButtons.forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const packageName = btn.getAttribute('data-package-name') || '';
      
      // Track solar package selection in Google Analytics
      trackPackageSelect(packageName);
      
      if (typeof openModalCallback === 'function') {
        openModalCallback(packageName);
      } else {
        // Fallback: trigger standard modal
        const modal = document.getElementById('get-started-modal');
        if (modal) {
          modal.classList.add('active');
          document.body.style.overflow = 'hidden';

          // Prefill inquiry message field if available
          const messageField = document.getElementById('message') || document.getElementById('gs-message');
          if (messageField) {
            messageField.value = `I would like to request a quotation and site assessment for the: ${packageName}.`;
          }
        }
      }
    });
  });

  // ─── View More / View Less Progressive Display ──────────────────────────────
  const toggleBtn = document.getElementById('packages-toggle-btn');
  const packagesGrid = document.getElementById('packages-grid');
  const packagesSection = document.getElementById('packages');

  if (toggleBtn && packagesGrid) {
    let isExpanded = false;

    toggleBtn.addEventListener('click', () => {
      isExpanded = !isExpanded;

      const toggleText = toggleBtn.querySelector('.packages__toggle-text');

      if (isExpanded) {
        packagesGrid.classList.add('is-expanded');
        toggleBtn.classList.add('is-active');
        toggleBtn.setAttribute('aria-expanded', 'true');
        if (toggleText) {
          toggleText.textContent = 'View Less';
        }
      } else {
        packagesGrid.classList.remove('is-expanded');
        toggleBtn.classList.remove('is-active');
        toggleBtn.setAttribute('aria-expanded', 'false');
        if (toggleText) {
          toggleText.textContent = 'View More Packages';
        }

        // Smoothly scroll back to top of packages section to keep context
        if (packagesSection) {
          const rect = packagesSection.getBoundingClientRect();
          if (rect.top < 0) {
            packagesSection.scrollIntoView({ behavior: 'smooth', block: 'start' });
          }
        }
      }
    });
  }
}
